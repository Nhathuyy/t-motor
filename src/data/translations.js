// Get translation with variable substitution
export function t(translations, lang, key, vars = {}) {
  let text = translations[lang][key] || key;
  Object.keys(vars).forEach((k) => {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
  });
  return text;
}
